"""Customer data connector abstraction.

``CustomerDataConnector`` is a small abstract interface for "get me the
current customer table as a dataframe". The idea is that the rest of the
pipeline (feature engineering, training, prediction) never imports pandas
I/O directly -- it depends on this interface, so the data source can be
swapped without touching downstream code.

This repository ships exactly one real, tested implementation:
``LocalSyntheticConnector``, which loads a synthetic, telecom-style
subscription customer dataset generated by ``churn.data.synthetic``, caching
it to a local parquet file so repeated runs are fast and fully reproducible
offline.

In a real production deployment, this interface would instead be backed by
a warehouse connector -- for example a ``SnowflakeConnector`` or
``BigQueryConnector`` built on SQLAlchemy / the vendor's Python driver,
reading from a governed customer/billing schema and handling credentials via
a secrets manager. That implementation is intentionally NOT included here:
this project has no access to a real company's warehouse, and shipping a
connector that isn't real and isn't tested would be worse than not having
one. Swapping one in later is a matter of adding a new subclass of
``CustomerDataConnector`` and pointing ``churn.config`` at it -- no changes
needed in ``features.py`` or ``modeling/``.
"""

from __future__ import annotations

from abc import ABC, abstractmethod
from pathlib import Path

import pandas as pd

from churn.data.synthetic import generate_synthetic_customers


class CustomerDataConnector(ABC):
    """Abstract source of the subscription-telecom customer table."""

    @abstractmethod
    def load_customers(self) -> pd.DataFrame:
        """Return the current customer table as a dataframe."""
        raise NotImplementedError


class LocalSyntheticConnector(CustomerDataConnector):
    """Loads the synthetic customer dataset, generating and caching it locally.

    On first call, generates ``n_customers`` synthetic rows with
    ``churn.data.synthetic.generate_synthetic_customers`` and writes them to
    ``cache_path`` as parquet. On subsequent calls, if the cache file
    already exists, it is read directly and the generator is not invoked
    again -- this keeps repeated pipeline runs fast and avoids silently
    regenerating (and potentially reseeding) data underneath a training run.

    Pass ``force_regenerate=True`` to ignore an existing cache file.
    """

    def __init__(
        self,
        cache_path: Path,
        n_customers: int = 20_000,
        seed: int = 42,
        force_regenerate: bool = False,
    ) -> None:
        self.cache_path = Path(cache_path)
        self.n_customers = n_customers
        self.seed = seed
        self.force_regenerate = force_regenerate

    def load_customers(self) -> pd.DataFrame:
        if self.cache_path.exists() and not self.force_regenerate:
            return pd.read_parquet(self.cache_path)

        df = generate_synthetic_customers(n_customers=self.n_customers, seed=self.seed)
        self.cache_path.parent.mkdir(parents=True, exist_ok=True)
        df.to_parquet(self.cache_path, index=False)
        return df
